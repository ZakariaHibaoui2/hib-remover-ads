// Generates src/rules/ads.json and src/content/selectors.js from tools/filters.mjs.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { AD_DOMAINS, URL_FILTERS, GENERIC_SELECTORS, YOUTUBE_SELECTORS } from './filters.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');

// Every resource type except the top-level page.
const SUBRESOURCES = [
  'sub_frame', 'stylesheet', 'script', 'image', 'font', 'object',
  'xmlhttprequest', 'ping', 'csp_report', 'media', 'websocket', 'other',
];

const unique = (list) => [...new Set(list)];
const domains = unique(AD_DOMAINS).sort();

const rules = [
  {
    id: 1,
    priority: 1,
    action: { type: 'block' },
    // Third-party only, so an ad company's own website still works when visited.
    condition: { requestDomains: domains, domainType: 'thirdParty', resourceTypes: SUBRESOURCES },
  },
  // Sites that wait on Google's ad tag before showing content get a no-op
  // stand-in instead of a hard block. Higher priority than the block above.
  ...['||securepubads.g.doubleclick.net/tag/js/gpt.js', '||googletagservices.com/tag/js/gpt.js']
    .map((urlFilter, i) => ({
      id: 100 + i,
      priority: 2,
      action: { type: 'redirect', redirect: { extensionPath: '/redirects/gpt.js' } },
      condition: { urlFilter, resourceTypes: ['script'] },
    })),
  ...unique(URL_FILTERS).map((urlFilter, i) => ({
    id: i + 2,
    priority: 1,
    action: { type: 'block' },
    condition: { urlFilter, resourceTypes: SUBRESOURCES },
  })),
];

writeFileSync(join(root, 'rules', 'ads.json'), JSON.stringify(rules, null, 2) + '\n');

const selectorsJs = `// Generated by tools/build.mjs. Do not edit by hand.
globalThis.HUSH_SELECTORS = ${JSON.stringify({
  generic: unique(GENERIC_SELECTORS),
  youtube: unique(YOUTUBE_SELECTORS),
}, null, 2)};
`;
writeFileSync(join(root, 'content', 'selectors.js'), selectorsJs);

console.log(`rules: ${rules.length} (${domains.length} domains), selectors: ${GENERIC_SELECTORS.length + YOUTUBE_SELECTORS.length}`);
